#!/bin/bash
# Installs eduwifi-watchdog as a systemd timer.
# Requires root. Usage: sudo ./install.sh [--networks "Net1,Net2"] [--uninstall]
set -e
cd "$(dirname "$0")"

CONF=/etc/eduwifi-watchdog.conf
BIN=/usr/local/sbin/eduwifi-watchdog.sh
LINK=/usr/local/bin/eduwifi-watchdog
UNITS="eduwifi-watchdog.service eduwifi-watchdog.timer"

usage() {
    cat <<EOF
Usage: sudo $0 [options]

Installs eduwifi-watchdog and enables its systemd timer. Requires root.
Without options it asks for the settings interactively.

Options:
  --networks "Net1,Net2"   NetworkManager profiles to retry, comma-separated,
                           in priority order (skips the networks question)
  --uninstall              Remove the script and the systemd units
                           (keeps $CONF)
  -h, --help               Show this help
EOF
}

NETWORKS_ARG=""
NETWORKS_SET=0
UNINSTALL=0
while [ $# -gt 0 ]; do
    case "$1" in
        --networks)
            [ $# -ge 2 ] || { usage >&2; exit 2; }
            NETWORKS_ARG=$2; NETWORKS_SET=1; shift 2 ;;
        --uninstall) UNINSTALL=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; exit 2 ;;
    esac
done

if [ "$(id -u)" -ne 0 ]; then
    echo "This installer requires root. Run it with: sudo $0 $*" >&2
    exit 1
fi

if [ "$UNINSTALL" -eq 1 ]; then
    systemctl disable --now eduwifi-watchdog.timer 2>/dev/null || true
    for u in $UNITS; do rm -f "/etc/systemd/system/$u"; done
    systemctl daemon-reload
    rm -f "$BIN" "$LINK"
    echo "Uninstalled. The configuration $CONF was kept (delete it manually if you want)."
    exit 0
fi

# Current values (if already installed) or autodetected ones
if [ -r "$CONF" ]; then
    # shellcheck source=/dev/null
    . "$CONF"
fi
IFACE=${IFACE:-$(nmcli -t -f DEVICE,TYPE device 2>/dev/null | awk -F: '$2=="wifi"{print $1; exit}')}
IFACE=${IFACE:-wlan0}

detect_module() {
    local m
    m=$(readlink -f "/sys/class/net/$1/device/driver/module" 2>/dev/null) && basename "$m"
}
detect_usb_id() {
    local d
    d=$(dirname "$(readlink -f "/sys/class/net/$1/device" 2>/dev/null)")
    [ -r "$d/idVendor" ] && echo "$(cat "$d/idVendor"):$(cat "$d/idProduct")"
}

ask() {  # ask VAR "question" default_value
    local reply
    if [ -t 0 ]; then
        read -rp "$2 [$3]: " reply
    fi
    printf -v "$1" '%s' "${reply:-$3}"
}

echo "== eduwifi-watchdog configuration =="
ask IFACE "Wi-Fi interface" "$IFACE"
ask MODULE "Kernel module to reload (empty = none)" "${MODULE:-$(detect_module "$IFACE")}"
ask USB_ID "USB adapter ID vendor:product (empty = no USB reset)" "${USB_ID:-$(detect_usb_id "$IFACE")}"

echo
echo "Wi-Fi networks saved in NetworkManager:"
nmcli -t -f NAME,TYPE connection show | awk -F: '$2=="802-11-wireless"{print "  - " $1}'
if [ "$NETWORKS_SET" -eq 1 ]; then
    NETWORKS=$NETWORKS_ARG
else
    ask NETWORKS "Networks to retry, comma-separated, in priority order" "$NETWORKS"
fi

# Trim spaces around each name and warn about unknown profiles
clean=""
IFS=',' read -ra nets <<< "$NETWORKS"
for n in "${nets[@]}"; do
    n=$(echo "$n" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')
    [ -n "$n" ] || continue
    nmcli -t -f NAME connection show | grep -qxF "$n" || echo "Warning: \"$n\" is not a NetworkManager profile"
    clean=${clean:+$clean,}$n
done
NETWORKS=$clean

cat > "$CONF" <<EOF
# Generated by install.sh on $(date '+%F %T'). See eduwifi-watchdog.conf.example.
IFACE=$(printf '%q' "$IFACE")
NETWORKS=$(printf '%q' "$NETWORKS")
MODULE=$(printf '%q' "$MODULE")
USB_ID=$(printf '%q' "$USB_ID")
FAILS_NEEDED=${FAILS_NEEDED:-2}
MAX_HARD_PER_HOUR=${MAX_HARD_PER_HOUR:-3}
CONNECT_TIMEOUT=${CONNECT_TIMEOUT:-30}
EOF
chmod 644 "$CONF"

install -m 755 eduwifi-watchdog.sh "$BIN"
ln -sf "$BIN" "$LINK"
install -m 644 $UNITS /etc/systemd/system/
systemctl daemon-reload
systemctl enable --now eduwifi-watchdog.timer

echo
echo "Configuration saved to $CONF:"
grep -v '^#' "$CONF"
echo
systemctl list-timers eduwifi-watchdog.timer --no-pager
echo
cat <<'EOF'
Useful commands:
  eduwifi-watchdog status             status and latest events
  eduwifi-watchdog disconnect         disconnect manually (the watchdog won't reconnect)
  eduwifi-watchdog off                turn the Wi-Fi off until you turn it back on
  eduwifi-watchdog on                 turn on and reconnect
  sudo eduwifi-watchdog test          simulate a hang and verify it recovers
  journalctl -t eduwifi-watchdog -f   follow the log
EOF
