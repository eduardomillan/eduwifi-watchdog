#!/bin/bash
# Installs eduwifi-watchdog as a systemd timer, plus its menu entry and translations.
# Requires root. Usage: sudo ./install.sh [--networks "Net1,Net2"] [--uninstall]
set -e
cd "$(dirname "$0")"

PROG=eduwifi-watchdog
CONF=/etc/$PROG.conf
BIN=/usr/local/sbin/$PROG.sh
LINK=/usr/local/bin/$PROG
UNITS="$PROG.service $PROG.timer"
DESKTOP=/usr/share/applications/$PROG.desktop
LOCALEDIR=/usr/share/locale

# Compile translations and the menu entry into a temporary build directory,
# so the installer itself can already speak the user's language
BUILD=$(mktemp -d)
trap 'rm -rf "$BUILD"' EXIT
HAVE_I18N=0
if po/compile.sh "$BUILD" >/dev/null 2>&1; then
    HAVE_I18N=1
fi
export TEXTDOMAIN=$PROG TEXTDOMAINDIR=$BUILD/locale
command -v gettext >/dev/null 2>&1 || gettext() { printf '%s' "$1"; }

say() {
    local fmt
    fmt=$(gettext "$1"); shift
    # shellcheck disable=SC2059
    printf "$fmt\n" "$@"
}

usage() {
    say 'Usage: sudo %s [options]

Installs eduwifi-watchdog, enables its systemd timer and adds a menu entry.
Requires root. Without options it asks for the settings interactively.

Options:
  --networks "Net1,Net2"   NetworkManager profiles to retry, comma-separated,
                           in priority order (skips the networks question)
  --uninstall              Remove the script, the systemd units, the menu entry
                           and the translations (keeps %s)
  -h, --help               Show this help' "$0" "$CONF"
}

NETWORKS_ARG=""
NETWORKS_SET=0
UNINSTALL=0
while [ $# -gt 0 ]; do
    case "$1" in
        --networks)
            [ $# -ge 2 ] || { usage >&2; exit 2; }
            NETWORKS_ARG=$2; NETWORKS_SET=1; shift 2 ;;
        --uninstall) UNINSTALL=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; exit 2 ;;
    esac
done

if [ "$(id -u)" -ne 0 ]; then
    say 'This installer requires root. Run it with: sudo %s' "$0" >&2
    exit 1
fi

if [ "$UNINSTALL" -eq 1 ]; then
    systemctl disable --now "$PROG.timer" 2>/dev/null || true
    for u in $UNITS; do rm -f "/etc/systemd/system/$u"; done
    systemctl daemon-reload
    rm -f "$BIN" "$LINK" "$DESKTOP"
    rm -f "$LOCALEDIR"/*/LC_MESSAGES/"$PROG".mo
    command -v update-desktop-database >/dev/null && update-desktop-database -q /usr/share/applications || true
    say 'Uninstalled. The configuration %s was kept (delete it manually if you want).' "$CONF"
    exit 0
fi

# Current values (if already installed) or autodetected ones
if [ -r "$CONF" ]; then
    # shellcheck source=/dev/null
    . "$CONF"
fi
IFACE=${IFACE:-$(nmcli -t -f DEVICE,TYPE device 2>/dev/null | awk -F: '$2=="wifi"{print $1; exit}')}
IFACE=${IFACE:-wlan0}

detect_module() {
    local m
    m=$(readlink -f "/sys/class/net/$1/device/driver/module" 2>/dev/null) && basename "$m"
}
detect_usb_id() {
    local d
    d=$(dirname "$(readlink -f "/sys/class/net/$1/device" 2>/dev/null)")
    [ -r "$d/idVendor" ] && echo "$(cat "$d/idVendor"):$(cat "$d/idProduct")"
}

ask() {  # ask VAR "question" default_value
    local reply
    if [ -t 0 ]; then
        read -rp "$(gettext "$2") [$3]: " reply
    fi
    printf -v "$1" '%s' "${reply:-$3}"
}

say '== eduwifi-watchdog configuration =='
ask IFACE 'Wi-Fi interface' "$IFACE"
ask MODULE 'Kernel module to reload (empty = none)' "${MODULE:-$(detect_module "$IFACE")}"
ask USB_ID 'USB adapter ID vendor:product (empty = no USB reset)' "${USB_ID:-$(detect_usb_id "$IFACE")}"

echo
say 'Wi-Fi networks saved in NetworkManager:'
nmcli -t -f NAME,TYPE connection show | awk -F: '$2=="802-11-wireless"{print "  - " $1}'
if [ "$NETWORKS_SET" -eq 1 ]; then
    NETWORKS=$NETWORKS_ARG
else
    ask NETWORKS 'Networks to retry, comma-separated, in priority order' "$NETWORKS"
fi

# Trim spaces around each name and warn about unknown profiles
clean=""
IFS=',' read -ra nets <<< "$NETWORKS"
for n in "${nets[@]}"; do
    n=$(echo "$n" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')
    [ -n "$n" ] || continue
    nmcli -t -f NAME connection show | grep -qxF "$n" || say 'Warning: "%s" is not a NetworkManager profile' "$n"
    clean=${clean:+$clean,}$n
done
NETWORKS=$clean

cat > "$CONF" <<EOF
# Generated by install.sh on $(date '+%F %T'). See $PROG.conf.example.
IFACE=$(printf '%q' "$IFACE")
NETWORKS=$(printf '%q' "$NETWORKS")
MODULE=$(printf '%q' "$MODULE")
USB_ID=$(printf '%q' "$USB_ID")
FAILS_NEEDED=${FAILS_NEEDED:-2}
MAX_HARD_PER_HOUR=${MAX_HARD_PER_HOUR:-3}
CONNECT_TIMEOUT=${CONNECT_TIMEOUT:-30}
EOF
chmod 644 "$CONF"

install -m 755 "$PROG.sh" "$BIN"
ln -sf "$BIN" "$LINK"
install -m 644 $UNITS /etc/systemd/system/
systemctl daemon-reload
systemctl enable --now "$PROG.timer"

# Menu entry and translations
if [ "$HAVE_I18N" -eq 1 ]; then
    install -m 644 "$BUILD/$PROG.desktop" "$DESKTOP"
    for mo in "$BUILD"/locale/*/LC_MESSAGES/"$PROG".mo; do
        lang=$(basename "$(dirname "$(dirname "$mo")")")
        install -D -m 644 "$mo" "$LOCALEDIR/$lang/LC_MESSAGES/$PROG.mo"
    done
else
    # Without gettext tools (msgfmt), install the untranslated English entry
    install -m 644 "$PROG.desktop.in" "$DESKTOP"
    say 'Warning: msgfmt not found (package gettext); installed without translations.'
fi
command -v update-desktop-database >/dev/null && update-desktop-database -q /usr/share/applications || true

# From here on, use the installed translations
export TEXTDOMAINDIR=$LOCALEDIR

echo
say 'Configuration saved to %s:' "$CONF"
grep -v '^#' "$CONF"
echo
systemctl list-timers "$PROG.timer" --no-pager
echo
say 'Menu entry: "Wi-Fi watchdog" (right-click it for quick actions).

Useful commands:
  eduwifi-watchdog status             status and latest events
  eduwifi-watchdog disconnect         disconnect manually (the watchdog will not reconnect)
  eduwifi-watchdog off                turn the Wi-Fi off until you turn it back on
  eduwifi-watchdog on                 turn on and reconnect
  eduwifi-watchdog gui                open the desktop dialog
  sudo eduwifi-watchdog test          simulate a hang and verify it recovers
  journalctl -t eduwifi-watchdog -f   follow the log'
